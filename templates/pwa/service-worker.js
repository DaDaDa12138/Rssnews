// settings.PWA_CACHE_VERSION, so a deploy that changes the shell retires every
// older cache in activate.
"use strict";

const CACHE_NAME = "newsblur-shell-{{ cache_version }}";
const OFFLINE_URL = "{% url 'pwa-offline' %}";
const PRECACHE_URLS = [
  "{% static 'css/common.css' %}",
  "{% static 'js/common_vendor.js' %}",
  "{% static 'js/common.js' %}",
  "{% static 'css/pwa-offline.css' %}?v={{ cache_version }}",
  "{{ MEDIA_PREFIX }}img/pwa/icon-192.png",
  "{{ MEDIA_PREFIX }}img/pwa/icon-512.png",
  "{{ MEDIA_PREFIX }}img/pwa/icon-maskable-512.png",
  "{{ MEDIA_PREFIX }}img/pwa/apple-touch-icon.png",
  OFFLINE_URL,
];

self.addEventListener("install", function (event) {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then(function (cache) {
        return cache.addAll(PRECACHE_URLS);
      })
      .then(function () {
        return self.skipWaiting();
      })
  );
});

self.addEventListener("activate", function (event) {
  event.waitUntil(
    caches
      .keys()
      .then(function (names) {
        return Promise.all(
          names
            .filter(function (name) {
              return name.indexOf("newsblur-shell-") === 0 && name !== CACHE_NAME;
            })
            .map(function (name) {
              return caches.delete(name);
            })
        );
      })
      .then(function () {
        return self.clients.claim();
      })
  );
});

function is_static_request(request) {
  var url = new URL(request.url);
  return (
    url.origin === self.location.origin &&
    (url.pathname.indexOf("/static/") === 0 || url.pathname.indexOf("{{ MEDIA_PREFIX }}img/pwa/") === 0)
  );
}

self.addEventListener("fetch", function (event) {
  var request = event.request;
  if (request.method !== "GET") return;

  if (request.mode === "navigate") {
    // Navigation is network-first: a signed-in reader must never receive a
    // cached copy of somebody else's HTML. The public offline shell is the only
    // page this worker stores. Only a rejected fetch means the network is gone;
    // an HTTP 404 or 500 is a real response and must reach the reader instead of
    // being mislabelled as "You're offline". A 302 arrives as an opaqueredirect
    // response, which is returned untouched for the browser to follow.
    event.respondWith(
      fetch(request).catch(function () {
        return caches.match(OFFLINE_URL);
      })
    );
    return;
  }

  if (!is_static_request(request)) return;

  // Static files are content-addressed by the pipeline, so cache-first is safe:
  // a changed bundle has a new URL and a new service worker install.
  event.respondWith(
    caches.match(request).then(function (cached) {
      if (cached) return cached;
      return fetch(request).then(function (response) {
        if (response.ok && response.type === "basic") {
          var copy = response.clone();
          caches.open(CACHE_NAME).then(function (cache) {
            cache.put(request, copy);
          });
        }
        return response;
      });
    })
  );
});
